copyFileSync(join(modules, "flag-icons", "LICENSE"), join(out, "flags", "FLAG-ICONS-LICENSE.txt"));

const versions = Object.fromEntries(
  ["cobe", "d3-geo", "topojson-client", "geist", "flag-icons"].map((p) => [
    p, JSON.parse(readFileSync(join(modules, p, "package.json"), "utf8")).version,
  ]),
);
const recorded = existsSync(join(out, "VERSIONS.json")) ? JSON.parse(readFileSync(join(out, "VERSIONS.json"), "utf8")) : {};   // build-borders.mjs records the map data here too
writeFileSync(join(out, "VERSIONS.json"), JSON.stringify({ ...recorded, ...versions, patches: PATCHES.map((p) => p.name) }, null, 2) + "\n");
